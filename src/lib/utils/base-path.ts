import { asset, resolve } from '$app/paths';
import type { AssetPath } from '$app/types';

/**
 * The deployment base path: '' in dev, '/stias-dh-ai-workshop-2026' in the
 * build. SvelteKit 3 removed `base` from `$app/paths`, but the locale helpers
 * still need the bare prefix to add to, and strip from, pathnames.
 * `resolve('')` is that prefix plus one slash, and stays absolute while
 * prerendering because `paths.relative` is off.
 */
export const base = resolve('').slice(0, -1);

/**
 * `asset()` for a path only known at run time. The content data stores
 * root-relative paths (`/images/…`), and the CFP and calendar downloads are
 * generated by the build, so neither matches the `AssetPath` union that
 * `svelte-kit sync` derives from static/ before the build has run.
 */
export function staticAsset(path: string): string {
	return asset(path.replace(/^\//, '') as AssetPath);
}
